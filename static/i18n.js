function savedLanguage() {
    const lang = saved("lang");     // static/common.js
    if (STRINGS[lang]) return lang;
    return (navigator.language || "pt").toLowerCase().startsWith("pt") ? "pt" : "en";
}

const LANG = savedLanguage();
const LOCALE = LANG === "pt" ? "pt-PT" : "en-GB";
const eur = new Intl.NumberFormat(LOCALE, { style: "currency", currency: "EUR" });

// A game's (or card's) name in the page's language: item.name_en / item.title_en when the page is
// in English and the game has an English name (IGDB's, or a moderator's), else the store's
function localName(item, field = "name") {
    return calmCaps((LANG === "en" && item[`${field}_en`]) || item[field]);
}

// A store title written in capitals, in normal case: "HELLRAISER REVIVAL" → "Hellraiser Revival",
// "KINGDOM HEARTS I-III" → "Kingdom Hearts I-III", "EA SPORTS FC 26" → "EA Sports FC 26". Titles
// with any small letter are left alone (they're written on purpose: "eFootball", "LEGO Batman")
const KEEP_CAPS = new Set(["FIFA", "LEGO", "UEFA", "NASCAR", "WRC", "NHL", "NFL", "NBA", "MLB", "EA", "FC", "UFC", "PGA",
    "WWE", "DLC", "VR", "HD", "GTA", "RPG", "UK", "USA", "TT", "F1", "MX", "ATV", "PES", "DBZ", "TMNT", "WWII", "II", "XL"]);
const SMALL_WORDS = new Set(["of", "the", "and", "a", "an", "in", "on", "to", "for", "at", "by", "or", "de", "da", "do", "das", "dos", "e", "o"]);

function calmCaps(text) {
    if (!text || /[a-zà-ÿ]/.test(text) || !/[A-ZÀ-Þ]{4}/.test(text)) return text;
    let first = true;
    return text.replace(/[A-Za-zÀ-ÿ0-9']+/g, word => {
        const lower = word.toLowerCase();
        const out = KEEP_CAPS.has(word) || /\d/.test(word) || /^[IVXLC]+$/.test(word) ? word
            : !first && SMALL_WORDS.has(lower) ? lower
            : lower.charAt(0).toUpperCase() + lower.slice(1);
        first = false;
        return out;
    });
}

// fallback: what to show when there's no text for `key` (by default the key itself)
// With {count: 1}, a "<key>_one" text is used when there is one (singular)
function t(key, vars = {}, fallback = key) {
    if (vars.count === 1 && STRINGS.pt[`${key}_one`]) key = `${key}_one`;
    const text = STRINGS[LANG][key] ?? STRINGS.pt[key] ?? fallback;
    return text.replace(/\{(\w+)\}/g, (_, name) => vars[name] ?? "");
}

function fmtNumber(n) {
    return Number(n).toLocaleString(LOCALE);
}

// Fixed HTML: data-i18n="key" sets the text; data-i18n-placeholder / -aria-label / -title the attribute
function applyI18n(root = document) {
    document.documentElement.lang = LANG;
    // data-icon: a line icon (common.js) before the text
    root.querySelectorAll("[data-i18n]").forEach(el => {
        if (el.dataset.icon && typeof icon === "function") el.innerHTML = `${icon(el.dataset.icon, 16)} ${esc(t(el.dataset.i18n))}`;
        else el.textContent = t(el.dataset.i18n);
    });
    const attributes = { placeholder: "i18nPlaceholder", "aria-label": "i18nAriaLabel", title: "i18nTitle" };
    for (const [attr, key] of Object.entries(attributes)) {
        root.querySelectorAll(`[data-i18n-${attr}]`).forEach(el => el.setAttribute(attr, t(el.dataset[key])));
    }
    renderLanguageSwitch();
}

// PT | EN buttons in the header (solid, the current one in blue). Switching reloads the page.
function renderLanguageSwitch() {
    const box = document.getElementById("lang-switch");
    if (!box) return;
    box.innerHTML = ["pt", "en"].map(lang =>
        `<button type="button" class="btn btn-sm ${lang === LANG ? "btn-primary" : "btn-secondary"}"
            data-lang="${lang}" aria-pressed="${lang === LANG}">${lang.toUpperCase()}</button>`).join("");
    box.querySelectorAll("[data-lang]").forEach(b => b.onclick = () => {
        if (b.dataset.lang === LANG) return;
        save("lang", b.dataset.lang);
        location.reload();
    });
}
